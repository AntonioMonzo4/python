#Es el arte de la organización y estructuración de un programa en partes independientes y reutilizables llamadas módulos.
#Un módulo es un archivo de Python que contiene definiciones y declaraciones de Python.
#La modularidad permite dividir un programa en partes más pequeñas y manejables, lo que facilita la comprensión,
#  el mantenimiento y la reutilización del código.
#Para crear un módulo, simplemente crea un archivo de Python con el código que deseas incluir en el módulo. 
# Por ejemplo, si quieres crear un módulo llamado "mi_modulo", puedes crear un archivo llamado "mi_modulo.py"
#  y escribir tu código dentro de ese archivo.
#Luego, para usar el módulo en otro archivo de Python, puedes importarlo usando la palabra clave "import". 
# Por ejemplo, si quieres usar el módulo "mi_modulo" en un archivo llamado "main.py", puedes escribir lo siguiente en "main.py":
#import mi_modulo   
